"""Export the existing effect algorithms to Vulkan GLSL with explicit resource layouts.

The coordinate shim retains the GLES algorithms' bottom-left pixel/UV convention
while Vulkan images, framebuffer attachments and scene uploads use top-left rows.
No shader runs through GLES in this export; glslc produces Vulkan SPIR-V.
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
JAVA = ROOT / "app/src/main/java/com/winlator/cmod/renderer"
OUT = ROOT / "app/src/main/cpp/winlator/renderer/vulkan/shaders"
SOURCES = {
    "color.frag": ("effects/ColorEffect.java", "getFragmentShader()"),
    "crt.frag": ("effects/CRTEffect.java", "getFragmentShader()"),
    "fsr_easu.frag": ("effects/FSREasuEffect.java", "getFragmentShader()"),
    "fsr_rcas.frag": ("effects/FSREffect.java", "getFragmentShader()"),
    "fxaa.frag": ("effects/FXAAEffect.java", "getFragmentShader()"),
    "hdr.frag": ("effects/HDREffect.java", "getFragmentShader()"),
    "ntsc.frag": ("effects/NTSCCombinedEffect.java", "getFragmentShader()"),
    "toon.frag": ("effects/ToonEffect.java", "getFragmentShader()"),
    "framegen.frag": ("lsfg/LSFGMaterial.java", "getFragmentShader()"),
    "motion.comp": ("lsfg/LSFGComputeMaterial.java", "String source ="),
}
TOKENS = re.compile(r'"(?:[^"\\]|\\.)*"|//[^\n]*|/\*.*?\*/|;', re.S)


def extract_java_shader(text: str, marker: str) -> str:
    start = text.index(marker) + len(marker)
    if marker != "String source =":
        start = text.index("return ", start) + len("return ")
    # RCAS embeds this constructor value into its GLES source. Vulkan keeps the
    # same value in a push constant instead of recompiling a pipeline per setting.
    text = text[:start] + re.sub(r'"\s*\+\s*stops\s*\+\s*"', 'uSharpnessStops', text[start:])
    strings = []
    end = start
    for token in TOKENS.finditer(text, start):
        end = token.end()
        value = token.group()
        if value == ";":
            break
        if value.startswith('"'):
            strings.append(json.loads(value))
    expression = text[start:end]
    if "String.join(" in expression:
        code = TOKENS.sub("", expression)
        code = re.sub(r"String\.join|new|CharSequence|String|[\s+(){},\[\]]", "", code)
        if code:
            raise ValueError("Shader array has a nonliteral expression: " + code[:100])
        separator, *strings = strings
        result = separator.join(strings)
        if "uSharpnessStops" in result:
            result = "uniform float uSharpnessStops;\n" + result
        return result
    # Reject expressions that would silently drop a Java interpolation.
    code = TOKENS.sub("", expression)
    if code.replace("+", "").strip():
        raise ValueError("Shader has a nonliteral Java expression: " + code[:100])
    return "".join(strings)


def convert(source: str, compute: bool) -> tuple[str, dict]:
    samplers, images, uniforms = [], [], []

    def resource(match):
        kind, names = match.group("type"), match.group("names")
        for name in map(str.strip, names.split(",")):
            if not re.fullmatch(r"[A-Za-z_]\w*", name):
                raise ValueError("Unsupported uniform: " + name)
            if kind == "sampler2D":
                samplers.append(name)
            elif kind == "image2D":
                images.append(name)
            else:
                uniforms.append((kind, name))
        return ""

    source = re.sub(r"(?m)^\s*#version[^\n]*", "", source)
    source = re.sub(r"\bprecision\s+\w+\s+\w+\s*;", "", source)
    declaration = r"(?:layout\([^)]*\)\s*)?uniform\s+(?:(?:writeonly|readonly|highp|mediump|lowp)\s+)*(?P<type>\w+)\s+(?P<names>[^;]+);"
    source = re.sub(declaration, resource, source)
    source = re.sub(r"(?m)^\s*(?:varying|in)\s+vec2\s+vUV\s*;", "", source)
    source = re.sub(r"\bout\s+vec4\s+outColor\s*;", "", source)
    source = source.replace("gl_FragColor", "outColor")
    uses_pixel_coordinates = "gl_FragCoord" in source
    if uses_pixel_coordinates:
        uniforms.append(("vec2", "_winxOutputSize"))
        source = source.replace("gl_FragCoord", "winxFragCoord()")
    source = re.sub(r"\b(?:texture2D|texture)\s*\(", "winxTexture(", source)
    source = re.sub(r"\btextureLod\s*\(", "winxTextureLod(", source)
    source = re.sub(r"\btexelFetch\s*\(", "winxTexelFetch(", source)
    for image in images:
        source = re.sub(r"imageStore\(\s*" + image + r"\s*,\s*p\s*,",
                        "imageStore(" + image + ", ivec2(p.x, imageSize(" + image + ").y - 1 - p.y),", source)

    header = ["#version 450", "// Generated by tools/export_vulkan_shaders.py; edit the original algorithm."]
    bindings = []
    for binding, name in enumerate(samplers):
        header.append(f"layout(set=0,binding={binding}) uniform sampler2D {name};")
        bindings.append({"name": name, "binding": binding, "type": "sampled_image"})
    for binding, name in enumerate(images, len(samplers)):
        header.append(f"layout(set=0,binding={binding},rgba8) uniform writeonly image2D {name};")
        bindings.append({"name": name, "binding": binding, "type": "storage_image"})
    offset, layout = 0, []
    alignments = {"int": (4, 4), "float": (4, 4), "vec2": (8, 8), "vec3": (16, 12), "vec4": (16, 16)}
    if uniforms:
        header.append("layout(push_constant) uniform EffectParameters {")
        for kind, name in uniforms:
            alignment, size = alignments[kind]
            offset = (offset + alignment - 1) // alignment * alignment
            header.append(f"    layout(offset={offset}) {kind} {name};")
            layout.append({"name": name, "type": kind, "offset": offset, "size": size})
            offset += size
        header.append("};")
    assert offset <= 128, "Exceeds Vulkan's guaranteed push constant size"
    if not compute:
        header.extend(["layout(location=0) in vec2 vUV;", "layout(location=0) out vec4 outColor;"])
    if samplers:
        header.extend([
            "vec4 winxTexture(sampler2D s, vec2 uv) { return texture(s,vec2(uv.x,1.0-uv.y)); }",
            "vec4 winxTextureLod(sampler2D s, vec2 uv, float lod) { return textureLod(s,vec2(uv.x,1.0-uv.y),lod); }",
            "vec4 winxTexelFetch(sampler2D s, ivec2 p, int lod) { return texelFetch(s,ivec2(p.x,textureSize(s,lod).y-1-p.y),lod); }",
        ])
    if uses_pixel_coordinates:
        header.append("vec4 winxFragCoord() { return vec4(gl_FragCoord.x,_winxOutputSize.y-gl_FragCoord.y,gl_FragCoord.zw); }")
    body = "\n".join(line.rstrip() for line in source.splitlines()).rstrip()
    return "\n".join(header) + "\n" + body + "\n", {"bindings": bindings, "push_bytes": (offset + 3) // 4 * 4, "uniforms": layout}


def export():
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for filename, (path, marker) in SOURCES.items():
        original = extract_java_shader((JAVA / path).read_text(encoding="utf-8"), marker)
        result, metadata = convert(original, filename.endswith(".comp"))
        metadata["source"] = path
        manifest[filename] = metadata
        (OUT / filename).write_text(result, encoding="utf-8", newline="\n")
    (OUT / "post.vert").write_text("""#version 450
layout(location=0) out vec2 vUV;
void main() {
    vec2 p=vec2((gl_VertexIndex<<1)&2,gl_VertexIndex&2);
    vUV=vec2(p.x,1.0-p.y);
    gl_Position=vec4(p*2.0-1.0,0.0,1.0);
}
""", encoding="utf-8", newline="\n")
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Exported {len(manifest)} effect stages and the post-process vertex shader.")


if __name__ == "__main__":
    export()
